const cart = [];
let currentCategory = "Pizze Novus";
let orderType = "new";

const menuDiv = document.getElementById("menu");
const cartDiv = document.getElementById("cart");
const categoriesDiv = document.querySelector(".categories");

function renderCategories() {
  categoriesDiv.innerHTML = "";

  Object.keys(menu).forEach(category => {
    const button = document.createElement("button");
    button.textContent = category;

    button.onclick = () => {
      currentCategory = category;
      renderMenu();
    };

    categoriesDiv.appendChild(button);
  });
}

function renderMenu() {
  menuDiv.innerHTML = "";

  menu[currentCategory].forEach(item => {
    const row = document.createElement("div");
    row.className = "menu-item";

    row.innerHTML = `
      <span>
        ${item.name}<br>
        <strong>€${item.price.toFixed(2)}</strong>
      </span>
      <button onclick="addToCart('${item.name}', ${item.price})">+</button>
    `;

    menuDiv.appendChild(row);
  });
}

function addToCart(name, price) {
  const existingItem = cart.find(item => item.name === name);

  if (existingItem) {
    existingItem.quantity += 1;
  } else {
    cart.push({ name, price, quantity: 1 });
  }

  renderCart();
}

function decreaseItem(index) {
  cart[index].quantity -= 1;

  if (cart[index].quantity <= 0) {
    cart.splice(index, 1);
  }

  renderCart();
}

function removeItem(index) {
  cart.splice(index, 1);
  renderCart();
}

function renderCart() {
  if (cart.length === 0) {
    cartDiv.innerHTML = "Nessun prodotto inserito";
    return;
  }

  let total = 0;
  cartDiv.innerHTML = "";

  cart.forEach((item, index) => {
    const lineTotal = item.price * item.quantity;
    total += lineTotal;

    cartDiv.innerHTML += `
      <div class="menu-item">
        <span>
          ${item.name} x${item.quantity}<br>
          <strong>€${lineTotal.toFixed(2)}</strong>
        </span>
        <div style="display:flex; gap:5px;">
          <button onclick="decreaseItem(${index})">-</button>
          <button onclick="addToCart('${item.name}', ${item.price})">+</button>
          <button onclick="removeItem(${index})">x</button>
        </div>
      </div>
    `;
  });

  cartDiv.innerHTML += `<hr><strong>Totale: €${total.toFixed(2)}</strong>`;
}

const newOrderBtn = document.getElementById("newOrderBtn");
const addOrderBtn = document.getElementById("addOrderBtn");

newOrderBtn.addEventListener("click", () => {
  orderType = "new";
  newOrderBtn.classList.add("active");
  addOrderBtn.classList.remove("active");
});

addOrderBtn.addEventListener("click", () => {
  orderType = "add";
  addOrderBtn.classList.add("active");
  newOrderBtn.classList.remove("active");
});

document.getElementById("sendOrder").addEventListener("click", async () => {
  const table = document.getElementById("tableNumber").value;
  const notes = document.getElementById("notes").value;

  if (!table) {
    alert("Inserisci il numero del tavolo");
    return;
  }

  if (cart.length === 0) {
    alert("Il carrello è vuoto");
    return;
  }

  const total = cart.reduce((sum, item) => {
    return sum + item.price * item.quantity;
  }, 0);

  const response = await fetch("/send-order", {
    method: "POST",
    headers: {
      "Content-Type": "application/json"
    },
    body: JSON.stringify({
      table,
      notes,
      cart,
      total,
      orderType
    })
  });

  const result = await response.json();

  if (result.success) {
    alert("Ordine inviato correttamente ✅");

    cart.length = 0;
    document.getElementById("notes").value = "";

    if (orderType === "new") {
      document.getElementById("tableNumber").value = "";
    }

    renderCart();
  } else {
    alert("Errore durante l'invio dell'ordine");
  }
});

renderCategories();
